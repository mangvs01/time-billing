"""Swiss QR-bill (QR-facture) payment slip, drawn on a reportlab page. Isolated module (mission BQR1): it imports nothing from the rest of the application.

The slip (210 x 106 mm: « Récépissé » on the left, « Section paiement » on the right) is generated by the MIT library « qrbill » 1.2.0 as an SVG, then converted
to a reportlab drawing with svglib. The library and its dependencies are embedded in the repository (app/vendor/, BQR4: see app/vendor/VENDOR.md, licences in app/vendor/licences/): no network access and no
external path are needed, and they are NOT in requirements.txt. They are imported lazily, so that this module can be imported, and the flag tested, without them.

Everything is off by default: QR_BILL_ENABLED (environment, « 1 », « true », « oui », « yes ») is only the global safeguard that makes the option available (BQR3);
the slip is added to an invoice only when its own box (invoices.qr_bill, header key « qr_bill ») is ticked.

Rules enforced here, before the library, with messages in plain French (QrBillError):
  - both addresses are STRUCTURED (name, street, number, postal code, city, country as separate fields): a free-text address block is refused (banks reject
    unstructured addresses from November 2026);
  - the IBAN is valid and Swiss or Liechtenstein; a QR-IBAN needs a QRR reference, a classic IBAN takes an ISO 11649 « SCOR » reference (RF…) or none (« NON »);
  - the amount is above zero, in CHF or EUR; the text fields only use characters allowed by the QR-bill standard.
"""
import io, os, sys
from decimal import Decimal, InvalidOperation, ROUND_HALF_UP

VENDOR_DIR = os.environ.get("QR_BILL_VENDOR_DIR") or os.path.join(os.path.dirname(os.path.abspath(__file__)), "vendor")
TRUTHY = ("1", "true", "yes", "oui", "on")
CURRENCIES = ("CHF", "EUR")
BILL_WIDTH_PT, BILL_HEIGHT_PT = 595.2756, 300.4724     # 210 x 106 mm as drawn by the library (svglib reads the viewBox)


class QrBillError(ValueError):
    """The QR-bill cannot be produced; the message is meant to be read by the user, in plain French."""


def enabled():
    """QR_BILL_ENABLED flag, read at each call (off when unset)."""
    return (os.environ.get("QR_BILL_ENABLED") or "").strip().lower() in TRUTHY


def _lib():
    """(QRBill class, svg2rlg) — the embedded libraries (app/vendor) are added to the path before the import, AFTER the regular packages, never in front."""
    if VENDOR_DIR and VENDOR_DIR not in sys.path: sys.path.append(VENDOR_DIR)
    try:
        from qrbill import QRBill
        from svglib.svglib import svg2rlg
    except ImportError as err:
        raise QrBillError("La bibliothèque de QR-facture n'est pas installée sur ce serveur (" + str(err) + ").")
    return QRBill, svg2rlg


# --- validation ---------------------------------------------------------------------------------------
# characters the standard allows in text fields: printable ASCII and the Latin letters of Western European languages
_ALLOWED_EXTRA = "àáâãäåæçèéêëìíîïñòóôõöøùúûüýÿœšžÀÁÂÃÄÅÆÇÈÉÊËÌÍÎÏÑÒÓÔÕÖØÙÚÛÜÝŸŒŠŽßÐðÞþ€£§°"
ADDRESS_FIELDS = (("name", "nom", 70, True), ("street", "rue", 70, False), ("house_num", "numéro", 16, False),
                  ("pcode", "code postal", 16, True), ("city", "localité", 35, True), ("country", "pays", 2, True))
UNSTRUCTURED_KEYS = ("address", "adresse", "line1", "line2", "billing_address", "issuer_address")


def _bad_chars(s):
    return sorted({ch for ch in s if not (0x20 <= ord(ch) < 0x7F or ch in _ALLOWED_EXTRA)})


def _clean(value, what, limit=None, required=True):
    s = " ".join(str(value or "").split())          # one line, single spaces: the standard forbids line breaks inside a field
    if not s:
        if required: raise QrBillError(f"{what} : champ obligatoire, il est vide.")
        return ""
    if bad := _bad_chars(s): raise QrBillError(f"{what} : caractère(s) non admis par la QR-facture : {' '.join(bad)}")
    if limit and len(s) > limit: raise QrBillError(f"{what} : {len(s)} caractères, {limit} au maximum.")
    return s


def structured_address(addr, role):
    """addr: dict with name, street, house_num, pcode, city, country (separate fields). Returns the clean dict for the library, or raises QrBillError.
    `role` is « du créancier » / « du client » for the messages."""
    if not isinstance(addr, dict):
        raise QrBillError(f"Adresse {role} : il faut des champs séparés (rue, numéro, code postal, localité, pays), pas un bloc de texte.")
    # « non structurée » only when no structured field at all is filled but a free-text block is (BQR4: otherwise the message names the missing field)
    loose = [k for k in UNSTRUCTURED_KEYS if (addr.get(k) or "").strip()] if not any((addr.get(k) or "").strip() for k in ("street", "house_num", "pcode", "city")) else []
    if loose:
        raise QrBillError(f"Adresse {role} non structurée : la QR-facture exige la rue, le numéro, le code postal, la localité et le pays dans des champs séparés. "
                          "Une adresse saisie en un seul bloc de texte est refusée par les banques.")
    out = {}
    for key, label, limit, required in ADDRESS_FIELDS:
        v = _clean(addr.get(key), f"Adresse {role}, {label}", limit, required)
        if key == "country":
            v = v.upper()
            if len(v) != 2 or not v.isalpha(): raise QrBillError(f"Adresse {role}, pays : code à 2 lettres attendu (CH, FR, DE…), reçu « {v} ».")
        if v: out[key] = v
    if "street" in out and out["street"][-1:].isdigit() and "house_num" not in out:
        raise QrBillError(f"Adresse {role} : le numéro est collé à la rue ; indiquer le numéro dans son propre champ.")
    return out


def check_iban(iban):
    """Compact upper-case IBAN, or QrBillError."""
    QRBill, _ = _lib()
    from qrbill import bill
    s = "".join(str(iban or "").split()).upper()
    if not s: raise QrBillError("IBAN du créancier : champ obligatoire, il est vide.")
    if not bill.iban.is_valid(s): raise QrBillError(f"IBAN du créancier invalide (« {iban} ») : vérifier les chiffres et la clé de contrôle.")
    if s[:2] not in bill.IBAN_ALLOWED_COUNTRIES: raise QrBillError("L'IBAN doit être suisse (CH) ou liechtensteinois (LI) pour une QR-facture.")
    return s


def check_amount(amount, currency):
    cur = (currency or "").strip().upper()
    if cur not in CURRENCIES: raise QrBillError("Devise : seules CHF et EUR sont admises par la QR-facture.")
    try: v = Decimal(str(amount).replace("'", "").replace(" ", "").replace(",", "."))
    except (InvalidOperation, ValueError): raise QrBillError("Montant illisible.")
    if not v.is_finite(): raise QrBillError("Montant illisible.")
    v = v.quantize(Decimal("0.01"), ROUND_HALF_UP)
    if v <= 0: raise QrBillError("Montant nul ou négatif : une QR-facture n'a de sens que pour un montant à payer supérieur à zéro.")
    if v > Decimal("999999999.99"): raise QrBillError("Montant trop élevé pour une QR-facture (999 999 999,99 au maximum).")
    return v, cur


def scor_reference(seed):
    """ISO 11649 creditor reference « RF » + 2 check digits + seed (letters and digits, 21 characters at most), e.g. built from the invoice number."""
    body = "".join(ch for ch in str(seed or "").upper() if ch.isalnum())
    if not body: raise QrBillError("Référence : rien à partir de quoi la construire (numéro de facture vide).")
    if len(body) > 21: raise QrBillError("Référence : 21 caractères (lettres et chiffres) au maximum après le préfixe RF.")
    digits = "".join(str(int(ch, 36)) for ch in body + "RF00")
    return f"RF{98 - int(digits) % 97:02d}{body}"


def check_reference(reference):
    """Normalised reference (« RF… » ISO 11649 or QRR digits) or '' for none; the library finishes the checks (check digits)."""
    r = "".join(str(reference or "").split()).upper()
    return r


# --- input checks used by the entry screens (BQR4): pure Python, no library needed -------------------------------
def iban_problem(iban, qr_iban=False):
    """None when `iban` is a well-formed IBAN with a correct check key (mod 97); for a QR-IBAN also Swiss / Liechtenstein with a QR institution number (30000-31999).
    Otherwise a short plain-French message. An empty value is not a problem here (the caller decides whether it is required)."""
    s = "".join(str(iban or "").split()).upper()
    if not s: return None
    if not s.isalnum() or not (15 <= len(s) <= 34) or not s[:2].isalpha() or not s[2:4].isdigit():
        return "IBAN invalide : il commence par 2 lettres (pays) et 2 chiffres, puis des chiffres et des lettres, sans caractère spécial."
    if int("".join(str(int(ch, 36)) for ch in s[4:] + s[:4])) % 97 != 1:
        return "IBAN invalide : la clé de contrôle ne correspond pas. Vérifier les chiffres (recopier le numéro depuis un document de la banque)."
    if qr_iban:
        if s[:2] not in ("CH", "LI"): return "Un QR-IBAN est un compte suisse ou liechtensteinois (il commence par CH ou LI)."
        if not s[4:9].isdigit() or not 30000 <= int(s[4:9]) <= 31999:
            return "Ce numéro n'est pas un QR-IBAN : la banque le donne à part, ses chiffres 5 à 9 sont compris entre 30000 et 31999. Laisser vide si vous n'en avez pas."
    return None


def address_problems(street, house_num, pcode, city, country, who="Adresse"):
    """Plain-French problems of a structured address typed in a form. A completely empty address is accepted (nothing typed yet); as soon as one field is
    filled, code postal, localité and pays are required (the street and its number stay optional, as in the standard)."""
    f = {"rue": (street, 70), "numéro": (house_num, 16), "code postal": (pcode, 16), "localité": (city, 35), "pays": (country, 2)}
    vals = {k: " ".join(str(v or "").split()) for k, (v, _) in f.items()}
    if not any(vals.values()): return []
    out = []
    for k in ("code postal", "localité", "pays"):
        if not vals[k]: out.append(f"{who}, {k} : à remplir (obligatoire dès qu'une partie de l'adresse est saisie).")
    for k, (_, limit) in f.items():
        v = vals[k]
        if v and (bad := _bad_chars(v)): out.append(f"{who}, {k} : caractère(s) non admis par la QR-facture : {' '.join(bad)}")
        elif len(v) > limit and k != "pays": out.append(f"{who}, {k} : {len(v)} caractères, {limit} au maximum.")
    if vals["pays"] and not (len(vals["pays"]) == 2 and vals["pays"].isalpha() and vals["pays"].isascii()):
        out.append(f"{who}, pays : code à 2 lettres attendu (CH, FR, BE, DE…), reçu « {vals['pays']} ».")
    if vals["rue"][-1:].isdigit() and not vals["numéro"]: out.append(f"{who} : le numéro est collé à la rue ; le mettre dans le champ « numéro ».")
    return out


def qrr_reference(seed):
    """QR reference (QRR) of 27 digits for a QR-IBAN: the digits of `seed` (the invoice number, « 2026-09 » -> 202609) padded with zeros on the left to 26
    digits + the modulo-10 recursive check digit of the Swiss payment standard. Without any digit in the seed (a draft has no number yet: its slip is marked « BROUILLON »)
    the reference is that of « 1 » (the library rejects an all-zero reference)."""
    digits = "".join(ch for ch in str(seed or "") if ch.isdigit()) or "1"
    if len(digits) > 26: raise QrBillError("Référence QRR : le numéro de facture compte plus de 26 chiffres.")
    body, carry = digits.zfill(26), 0
    for ch in body: carry = (0, 9, 4, 6, 8, 2, 7, 1, 3, 5)[(carry + int(ch)) % 10]
    return body + str((10 - carry) % 10)


# --- bill ----------------------------------------------------------------------------------------------
def build_bill(creditor, iban, amount, currency="CHF", debtor=None, reference=None, message="", language="fr"):
    """Validated library object. creditor/debtor: structured address dicts; debtor may be None (the slip then leaves a box to fill in by hand)."""
    QRBill, _ = _lib()
    cred = structured_address(creditor, "du créancier")
    deb = structured_address(debtor, "du client") if debtor else None
    account = check_iban(iban)
    value, cur = check_amount(amount, currency)
    ref = check_reference(reference)
    msg = _clean(message, "Message", 140, required=False)
    try:
        return QRBill(account=account, creditor=cred, debtor=deb, amount=value, currency=cur, reference_number=ref or None,
                      additional_information=msg, language=language if language in ("fr", "de", "it", "en") else "fr")
    except ValueError as err:
        raise QrBillError(_french(str(err)))


def _french(msg):
    table = (("QR-IBAN requires a QRR", "Un QR-IBAN (IBAN de QR-facture) exige une référence QRR à 27 chiffres ; une référence ISO 11649 (RF…) ou aucune référence ne suffit pas."),
             ("QRR reference number is only allowed for a QR-IBAN", "Une référence QRR à 27 chiffres n'est admise qu'avec un QR-IBAN ; avec un IBAN classique, utiliser une référence « RF… » ou aucune."),
             ("reference number is invalid", "Référence invalide : la clé de contrôle ne correspond pas (RF… ISO 11649 ou QRR à 27 chiffres)."),
             ("IBAN is not valid", "IBAN du créancier invalide."), ("IBAN must start with", "L'IBAN doit être suisse (CH) ou liechtensteinois (LI)."),
             ("creditor address is invalid", "Adresse du créancier invalide : " + msg.split(":", 1)[-1].strip()),
             ("debtor address is invalid", "Adresse du client invalide : " + msg.split(":", 1)[-1].strip()),
             ("Additional information", "Message trop long (140 caractères au maximum)."))
    return next((fr for en, fr in table if en in msg), "QR-facture refusée : " + msg)


def bill_svg(bill):
    out = io.StringIO(); bill.as_svg(out); return out.getvalue()


def bill_drawing(bill):
    """reportlab Drawing of the slip, 595.28 x 300.47 pt (210 x 106 mm), origin at its bottom-left corner."""
    _, svg2rlg = _lib()
    d = svg2rlg(io.BytesIO(bill_svg(bill).encode("utf-8")))
    if d is None: raise QrBillError("Le bulletin de QR-facture n'a pas pu être converti en dessin PDF.")
    return d


def draw_bill(c, bill, x=0, y=0):
    """Draw the slip on reportlab canvas `c` with its bottom-left corner at (x, y) points from the page's bottom-left (0, 0 = the foot of an A4 page)."""
    from reportlab.graphics import renderPDF
    renderPDF.draw(bill_drawing(bill), c, x, y)
    c.setFillColorRGB(0, 0, 0); c.setStrokeColorRGB(0, 0, 0)


def payment_page(c, bill, title=None):
    """Whole A4 portrait page: optional title at the top, the slip in the bottom 106 mm. The caller owns showPage()."""
    page_h = c._pagesize[1]
    if title:
        c.setFont("Helvetica", 10); c.drawString(50, page_h - 60, title)
    draw_bill(c, bill, 0, 0)


# --- from an invoice header (the only place that knows the application's field names) ----------------------
ISSUER_KEYS = {"street": "issuer_street", "house_num": "issuer_house_num", "pcode": "issuer_pcode", "city": "issuer_city", "country": "issuer_country"}
CLIENT_KEYS = {"street": "client_street", "house_num": "client_house_num", "pcode": "client_pcode", "city": "client_city", "country": "client_country"}


def inputs_from_header(h):
    """Keyword arguments of build_bill from a frozen-style invoice header `h` (see invoice_service.live_data). Raises QrBillError when data is missing.
    BQR4: nothing is invented — a missing country stays missing (the module then says « pays : champ obligatoire »). A QR-IBAN of the issuer
    (settings key qr_iban) replaces the classic IBAN on the slip and brings a QRR reference built from the invoice number; without it, SCOR."""
    s = h.get("issuer") or {}
    creditor = {"name": s.get("account_holder") or s.get("issuer_name")}
    creditor.update({k: s.get(v) for k, v in ISSUER_KEYS.items()})
    debtor = {"name": h.get("client_legal_name") or h.get("client")}
    debtor.update({k: h.get(v) for k, v in CLIENT_KEYS.items()})
    # today's free-text blocks are passed along only so that the refusal can say « adresse non structurée » rather than « code postal vide »
    creditor["issuer_address"] = s.get("issuer_address"); debtor["billing_address"] = h.get("billing_address")
    a = h.get("amounts") or {}
    amount = h["net_due"] if h.get("offsets") else a.get("ttc")
    number = h.get("number")
    qr_iban = (s.get("qr_iban") or "").strip()
    if qr_iban: iban, reference = qr_iban, qrr_reference(number)
    else: iban, reference = s.get("iban"), scor_reference(number) if number else None
    return dict(creditor=creditor, iban=iban, amount=amount, currency=h.get("currency") or "CHF", debtor=debtor,
                reference=reference, message=f"Facture {number}" if number else "")


def assess(h):
    """(bill, warning) for an invoice header `h`. Never raises. bill is None when no slip is to be printed:
      - warning is None  : the QR-bill does not apply (the creditor IBAN is valid but not Swiss / Liechtenstein) -> omitted without any message;
      - warning is text  : the slip is omitted and the text, in plain French, tells why (missing or unstructured address, invalid IBAN, bad amount...)."""
    try:
        kw = inputs_from_header(h)
        s = "".join(str(kw.get("iban") or "").split()).upper()
        if s[:2].isalpha() and s[:2] not in ("CH", "LI") and _iban_checksum_ok(s): return None, None
        return build_bill(**kw), None
    except QrBillError as err:
        return None, str(err)


def _iban_checksum_ok(s):
    _lib(); from stdnum import iban
    return bool(iban.is_valid(s))


def wanted(h):
    """BQR3: the QR-bill is added to THIS invoice only when the global safeguard is on AND the box « Ajouter la QR-facture » was ticked on the invoice."""
    return bool(h.get("qr_bill")) and enabled()


def availability(h):
    """(state, why) for the box on a draft: « off » (global safeguard off: no box at all), « unsupported » (the account is not Swiss / Liechtenstein: box greyed,
    why = short explanation), « ok » (the box may be ticked)."""
    if not enabled(): return "off", None
    bill, warning = assess(h)
    if bill is None and warning is None: return "unsupported", "pas de bulletin pour ce compte (IBAN ni suisse ni liechtensteinois)"
    return "ok", None


def blocking_problem(h):
    """BQR3: None when the box is not ticked (or the safeguard is off, or the account does not apply) or the slip can be made; else the plain-French reason that
    BLOCKS issuance. The way out is always to untick the box."""
    if not wanted(h): return None
    bill, why = assess(h)
    if bill is None and why is None: return None
    if "client_addr_verified" in h and not h["client_addr_verified"]:
        return ("Adresse du client à confirmer : les champs de l'adresse (rue, numéro, code postal, localité, pays) n'ont pas encore été validés. "
                "Les relire dans la fiche du mandat puis cocher « adresse vérifiée »" + (" (autre point à corriger : " + why + ")" if why else ""))
    return why


def page_for_header(c, h, issued=True):
    """Insertion point used by pdf_layout.render_invoice (only when wanted(h)): adds ONE portrait page holding the slip after the page being drawn.
    A draft prints the mention « BROUILLON » on it. When the slip cannot be made (or does not apply) nothing is added and nothing is raised: for a draft the
    reason is shown by the blocking check 15 of the issue page, and an invoice cannot be issued with that check failing."""
    bill, _ = assess(h)
    if bill is None: return None
    c.showPage()
    payment_page(c, bill, "Section paiement — facture " + str(h.get("number") or "(brouillon)"))
    if not issued:
        c.setFont("Helvetica-Bold", 14); c.setFillColorRGB(0.75, 0.1, 0.1)
        c.drawString(50, c._pagesize[1] - 85, "BROUILLON — bulletin non valable, facture non émise")
        c.setFillColorRGB(0, 0, 0)
    return bill


